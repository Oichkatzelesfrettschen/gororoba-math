(** Rocq bridge of lean/GororobaMath/CayleyDickson/E8ConjugationIdeal.lean: the conjugation Phi maps the germ
    ideal J of N- onto the one of N+, over the integers.

    Convention: jm and jp of E8ConjugationIdeal.v list the 27 generators of J_N- and J_N+ in the variables
    i, s1, ..., s9, in the order of the Lean definitions jm and jp (Lean index k = 0, ..., 26 is the list
    position k + 1). Phi is the substitution i -> -i, s4 -> -s5, s5 -> s4, s7 <-> s8; phi_signs is the Lean
    phiSign as a list of booleans (true is +1, false is -1) and signed applies it. The flip negates s3, s5, s6.

    Lean theorem and substituted values (Lean A := Z, the variables i, s1, ..., s9 := the Rocq arguments):
    - jm_phi_Z is CayleyDickson.E8Conjugation.jm_phi at A := Z: Phi of generator k of J_N- is phiSign k times
      generator k of J_N+.
    - jm_phi_flip_Z is CayleyDickson.E8Conjugation.jm_phi_flip at A := Z: Phi after the flip of s3, s5, s6 maps
      generator k of J_N- to generator k of J_N+ with no sign. phi_flip_generators states it over every
      commutative ring, as jm_phi_flip does over every CommRing.
    - conjugation_ideal_bridge is CayleyDickson.E8Conjugation.span_phi_jm at the ring Z, with the variables
      replaced by integers: the ideal generated by the images of the generators of J_N- equals the ideal generated
      by the generators of J_N+, in gen_ideal. The Lean theorems span_phi_jm and span_phiFlip_jm hold in
      MvPolynomial (Fin 10) R for every commutative ring R, with the ten variables as indeterminates, and
      span_phiFlip_jm is the same statement for Phi after the flip; the Rocq statement fixes R = Z and quantifies
      over the values of the variables, so it is narrower. *)

From Stdlib Require Import ZArith List Ring Ring_theory InitialRing.
Require Import E8ConjugationIdeal.
Import ListNotations.

Declare Scope e8_bridge_scope.

Section FlipBridge.

Variable R : Type.
Variables (rO rI : R) (radd rmul rsub : R -> R -> R) (ropp : R -> R).
Hypothesis Rth : ring_theory rO rI radd rmul rsub ropp (@eq R).
Add Ring e8_bridge_ring : Rth.

Local Notation "x + y" := (radd x y) : e8_bridge_scope.
Local Notation "x * y" := (rmul x y) : e8_bridge_scope.
Local Notation "- x" := (ropp x) : e8_bridge_scope.
Local Open Scope e8_bridge_scope.

(** Phi after the flip of s3, s5, s6 maps generator k of J_N- to generator k of J_N+, by ring on each pair. *)
Theorem phi_flip_generators : forall i s1 s2 s3 s4 s5 s6 s7 s8 s9,
  jm R rO rI radd rmul ropp (- i) s1 s2 (- s3) (- s5) (- s4) (- s6) s8 s7 s9
  = jp R rO rI radd rmul ropp i s1 s2 s3 s4 s5 s6 s7 s8 s9.
Proof.
  intros. unfold jm, jp.
  repeat (apply (cons_eq R); [ring |]). reflexivity.
Qed.

End FlipBridge.

Theorem jm_phi_Z : forall i s1 s2 s3 s4 s5 s6 s7 s8 s9,
  jm_Z (- i) s1 s2 s3 (- s5) s4 s6 s8 s7 s9 = signed Z Z.opp phi_signs (jp_Z i s1 s2 s3 s4 s5 s6 s7 s8 s9).
Proof. intros. exact (phi_generators Z 0%Z 1%Z Z.add Z.mul Z.sub Z.opp Zth i s1 s2 s3 s4 s5 s6 s7 s8 s9). Qed.

Theorem jm_phi_flip_Z : forall i s1 s2 s3 s4 s5 s6 s7 s8 s9,
  jm_Z (- i) s1 s2 (- s3) (- s5) (- s4) (- s6) s8 s7 s9 = jp_Z i s1 s2 s3 s4 s5 s6 s7 s8 s9.
Proof. intros. exact (phi_flip_generators Z 0%Z 1%Z Z.add Z.mul Z.sub Z.opp Zth i s1 s2 s3 s4 s5 s6 s7 s8 s9). Qed.

Theorem conjugation_ideal_bridge : forall i s1 s2 s3 s4 s5 s6 s7 s8 s9 x,
  gen_ideal Z 0%Z Z.add Z.mul (jm_Z (- i) s1 s2 s3 (- s5) s4 s6 s8 s7 s9)%Z x
  <-> gen_ideal Z 0%Z Z.add Z.mul (jp_Z i s1 s2 s3 s4 s5 s6 s7 s8 s9) x.
Proof. intros. apply conjugation_ideal_Z. Qed.

Print Assumptions jm_phi_Z.
Print Assumptions jm_phi_flip_Z.
Print Assumptions conjugation_ideal_bridge.
