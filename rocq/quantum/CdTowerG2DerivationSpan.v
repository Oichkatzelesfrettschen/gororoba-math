Definition gaussian_eqb (x y : Z * Z) : bool := Z.eqb (fst x) (fst y) && Z.eqb (snd x) (snd y).

Lemma gaussian_eqb_eq x y : gaussian_eqb x y = true -> x = y.
Proof.
  destruct x as [a b], y as [c e]. unfold gaussian_eqb. cbn [fst snd]. intro E.
  apply andb_prop in E as [E1 E2]. apply Z.eqb_eq in E1, E2. subst. reflexivity.
Qed.

(** [structure_table] holds coordinate m of e_a e_b at position (a, b, m), computed over the Gaussian integers. *)
Definition structure_table : list (list (list (Z * Z))) :=
  Eval vm_compute in
    map (fun a => map (fun b => map (fun m =>
      GaussianG2.BC.TA.coord 4 (GaussianG2.BC.TA.mul 4 (GaussianG2.BC.SA.basis 4 a) (GaussianG2.BC.SA.basis 4 b)) m)
      (seq 0 16)) (seq 0 16)) (seq 0 16).

Definition structure (a b m : nat) : GaussianIntegers.t :=
  nth m (nth b (nth a structure_table []) []) GaussianIntegers.zero.

Module G2DerivationSpan (D : CommutativeRing) (H : RingHom GaussianIntegers D).
Module LS := LeibnizSystem GaussianIntegers D H.
Module SC := SplittingCertificate GaussianIntegers D H.
Import LS.BC.

Add Ring g2_span_target : D.ring_th.

Lemma structure_source : forall a b m,
  (a < Nat.pow 2 4)%nat -> (b < Nat.pow 2 4)%nat -> (m < Nat.pow 2 4)%nat ->
  TA.coord 4 (TA.mul 4 (SA.basis 4 a) (SA.basis 4 b)) m = structure a b m.
Proof.
  intros a b m Ha Hb Hm. apply gaussian_eqb_eq.
  assert (E : forall_below 16 (fun a => forall_below 16 (fun b => forall_below 16 (fun m =>
                gaussian_eqb (TA.coord 4 (TA.mul 4 (SA.basis 4 a) (SA.basis 4 b)) m) (structure a b m)))) =
              true) by (vm_compute; reflexivity).
  exact (forall_below_spec _ _ (forall_below_spec _ _ (forall_below_spec _ _ E a Ha) b Hb) m Hm).
Qed.

Lemma equations_in_range : forallb (LS.in_range 4) G2SpanTables.equations = true.
Proof. vm_compute. reflexivity. Qed.

Lemma tables_well_formed :
  Nat.eqb (length G2SpanTables.equations) 242 = true /\
  SC.LC.sparse_shape G2SpanTables.back 256 242 = true.
Proof. split; vm_compute; reflexivity. Qed.

Definition matrix : nat -> nat -> GaussianIntegers.t := LS.matrix 4 structure G2SpanTables.equations.

Definition back (i r : nat) : GaussianIntegers.t := SC.LC.sparse_entry G2SpanTables.back i r.

(** [table t] is the table of D_(t+1) of CdTowerG2Derivations.v. *)
Definition table (t m : nat) : TA.cd 4 := GaussianG2.images t m.

Definition vectors (i t : nat) : GaussianIntegers.t := TA.coord 4 (table t (i / 16)) (i mod 16).

Definition functionals (t j : nat) : GaussianIntegers.t :=
  GaussianIntegers.mul G2SpanTables.scalar (SC.LC.sparse_entry G2DerivationTables.independence_left t j).

Lemma splitting : forall i j, (i < 256)%nat -> (j < 256)%nat ->
  GaussianIntegers.add
    (SC.SA.dsum 242 (fun r => GaussianIntegers.mul (back i r) (matrix r j)))
    (SC.SA.dsum 14 (fun t => GaussianIntegers.mul (vectors i t) (functionals t j))) =
  if Nat.eqb j i then G2SpanTables.scalar else GaussianIntegers.zero.
Proof.
  intros i j Hi Hj. apply gaussian_eqb_eq.
  assert (E : forall_below 256 (fun i => forall_below 256 (fun j =>
                gaussian_eqb
                  (GaussianIntegers.add
                     (SC.SA.dsum 242 (fun r => GaussianIntegers.mul (back i r) (matrix r j)))
                     (SC.SA.dsum 14 (fun t => GaussianIntegers.mul (vectors i t) (functionals t j))))
                  (if Nat.eqb j i then G2SpanTables.scalar else GaussianIntegers.zero))) = true)
    by (vm_compute; reflexivity).
  exact (forall_below_spec _ _ (forall_below_spec _ _ E i Hi) j Hj).
Qed.

Lemma dsum_agree n (g : nat -> D.t) : SB.dsum n g = SC.SB.dsum n g.
Proof. induction n as [|m IH]; cbn [SB.dsum SC.SB.dsum]; [reflexivity | rewrite IH; reflexivity]. Qed.

Lemma flat_div m q : (q < 16)%nat -> ((16 * m + q) / 16 = m)%nat.
Proof. intro Hq. rewrite Nat.mul_comm, Nat.add_comm, Nat.div_add, Nat.div_small by lia. reflexivity. Qed.

Lemma flat_mod m q : (q < 16)%nat -> ((16 * m + q) mod 16 = q)%nat.
Proof. intro Hq. rewrite Nat.mul_comm, Nat.add_comm, Nat.Div0.mod_add. apply Nat.mod_small. exact Hq. Qed.

(** Coordinate c of the image of the basis unit e_m under the map with prescribed images. *)
Lemma target_map_basis_coord k (images : nat -> TA.cd k) m c : (m < Nat.pow 2 k)%nat ->
  TB.coord k (target_map k images (SB.basis k m)) c = H.h (TA.coord k (images m) c).
Proof.
  intro Hm. unfold target_map. rewrite SB.coord_tsum.
  rewrite (SB.dsum_ext _ _
             (fun i => D.mul (TB.coord k (tmap k (images i)) c) (if Nat.eqb i m then D.one else D.zero))).
  - rewrite SB.dsum_delta, (proj2 (Nat.ltb_lt _ _) Hm), <- tmap_coord. reflexivity.
  - intros i Hi. rewrite TB.coord_scale, SB.coord_basis by assumption.
    rewrite (Nat.eqb_sym m i). ring.
Qed.

Lemma combination_linear n (c : nat -> D.t) :
  SB.linear 4 (fun x => SB.tsum 4 n (fun t => TB.scale 4 (c t) (target_map 4 (table t) x))).
Proof.
  split; intros; apply TB.ext; intros i _; rewrite ?TB.coord_add, ?TB.coord_scale, !SB.coord_tsum.
  - induction n as [|m IH]; cbn [SB.dsum]; [ring |].
    rewrite IH, !TB.coord_scale, (proj1 (target_map_linear 4 (table m))), TB.coord_add. ring.
  - induction n as [|m IH]; cbn [SB.dsum]; [ring |].
    rewrite IH, !TB.coord_scale, (proj2 (target_map_linear 4 (table m))), TB.coord_scale. ring.
Qed.

Section Derivation.

Variable F : TB.cd 4 -> TB.cd 4.

Hypothesis F_linear : SB.linear 4 F.

Hypothesis F_leibniz : forall a b, (a < Nat.pow 2 4)%nat -> (b < Nat.pow 2 4)%nat ->
  F (TB.mul 4 (SB.basis 4 a) (SB.basis 4 b)) =
  TB.add 4 (TB.mul 4 (F (SB.basis 4 a)) (SB.basis 4 b)) (TB.mul 4 (SB.basis 4 a) (F (SB.basis 4 b))).

Definition unknown : nat -> D.t := LS.unknown 4 F.

(** The coefficient of D_(t+1) in h(d) F. *)
Definition span_coefficient (t : nat) : D.t := SC.coefficient 256 functionals unknown t.

Lemma solved : SC.solution 242 256 matrix unknown.
Proof.
  unfold SC.solution. intros r Hr. rewrite <- dsum_agree.
  exact (LS.system_solved 4 structure structure_source F F_linear F_leibniz G2SpanTables.equations
           equations_in_range r Hr).
Qed.

Theorem entries_spanned : forall m q, (m < 16)%nat -> (q < 16)%nat ->
  D.mul (H.h G2SpanTables.scalar) (TB.coord 4 (F (SB.basis 4 m)) q) =
  SB.dsum 14 (fun t => D.mul (H.h (TA.coord 4 (table t m) q)) (span_coefficient t)).
Proof.
  intros m q Hm Hq.
  assert (Hj : (16 * m + q < 256)%nat) by lia.
  pose proof (SC.solutions_spanned 242 256 14 G2SpanTables.scalar matrix back vectors functionals
                splitting unknown solved (16 * m + q)%nat Hj) as E.
  unfold unknown at 1, LS.unknown, LS.entry, vectors in E.
  change (Nat.pow 2 4) with 16%nat in E.
  rewrite !(flat_div m q Hq), !(flat_mod m q Hq) in E.
  rewrite dsum_agree. exact E.
Qed.

Theorem derivations_spanned : forall x,
  TB.scale 4 (H.h G2SpanTables.scalar) (F x) =
  SB.tsum 4 14 (fun t => TB.scale 4 (span_coefficient t) (target_map 4 (table t) x)).
Proof.
  apply (SB.linear_ext 4 (fun x => TB.scale 4 (H.h G2SpanTables.scalar) (F x))
           (fun x => SB.tsum 4 14 (fun t => TB.scale 4 (span_coefficient t) (target_map 4 (table t) x)))).
  - split; intros; [rewrite (proj1 F_linear) | rewrite (proj2 F_linear)]; apply TB.ext; intros i _;
      repeat (rewrite TB.coord_add || rewrite TB.coord_scale); ring.
  - apply combination_linear.
  - intros m Hm. apply TB.ext. intros q Hq.
    rewrite TB.coord_scale, SB.coord_tsum, (entries_spanned m q Hm Hq). apply SB.dsum_ext. intros t _.
    rewrite TB.coord_scale, target_map_basis_coord by exact Hm. ring.
Qed.

(** With an inverse of h(d), F is the combination of the 14 derivations with coefficients u c_t. *)
Theorem derivations_spanned_invertible (u : D.t) : D.mul u (H.h G2SpanTables.scalar) = D.one ->
  forall x, F x = SB.tsum 4 14 (fun t => TB.scale 4 (D.mul u (span_coefficient t)) (target_map 4 (table t) x)).
Proof.
  intros U x. apply TB.ext. intros i _.
  pose proof (f_equal (fun w => TB.coord 4 w i) (derivations_spanned x)) as E. cbn beta in E.
  rewrite TB.coord_scale, SB.coord_tsum in E. rewrite SB.coord_tsum.
  transitivity (D.mul u (D.mul (H.h G2SpanTables.scalar) (TB.coord 4 (F x) i))).
  - transitivity (D.mul (D.mul u (H.h G2SpanTables.scalar)) (TB.coord 4 (F x) i)); [rewrite U; ring | ring].
  - rewrite E. clear E. generalize 14%nat. intro n.
    induction n as [|p IH]; cbn [SB.dsum]; [ring |]. rewrite <- IH, !TB.coord_scale. ring.
Qed.

End Derivation.

End G2DerivationSpan.

