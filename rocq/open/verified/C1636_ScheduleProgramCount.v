(** * C-1636: a straight-line program whose evaluation counts the multiplications of the Cariow 2013 sedenion schedule.

    Convention: [R16], [r16_to_sed], [r16_cariow2013_sedenion_mul] and
    [C1636_cariow2013_sedenion_mul_eq] are those of
    C1636_Cariow2013SedenionSchedule; [r16_nth] and [sparse_terms] (row i
    lists the pairs (index into b, index into a) of the products that
    coordinate i of the sparse correction sums) are those of
    C1636_ScheduleProductCount.  A [program] is a list of instructions and
    a list of output registers.  The instruction at position n writes
    register n, so the registers are the positions of the list, and an
    operand names an earlier register.  The instructions are: load the
    coordinate a_i or b_j of an input; add or subtract two registers;
    scale a register by a constant real number ([IScale], the constant is
    part of the program and does not depend on a or b); multiply two
    registers ([IMul], the only instruction that forms a product of two
    variable quantities).  [run p a b] executes the instructions on the
    inputs a and b and returns the values of the output registers;
    [mul_count p] counts the [IMul] instructions of p by structural
    recursion on the instruction list, so it reads the program text and
    runs nothing.

    [cariow_program] is generated by Gallina functions from the stages of
    the schedule: loads of the sixteen coordinates of a and of b; the
    Hadamard forward transform of each (four butterfly stages of sixteen
    additions and subtractions, strides 8, 4, 2, 1); scaling of the
    transform of b by 1/16; sixteen pointwise products; the Hadamard
    reverse transform (strides 1, 2, 4, 8); the sparse correction, one
    block per row of [sparse_terms] (its products, their sum, scaling by 2);
    and the final combination, which subtracts the correction from the
    Toeplitz part and negates the first coordinate by swapping the operands
    of its subtraction.

    The module proves:
    - [cariow_program_correct]: for all a and b, [run cariow_program a b]
      is the list of the sixteen coordinates of
      [r16_cariow2013_sedenion_mul a b];
    - [cariow_program_mul_count]: [mul_count cariow_program = 122];
    - [C1636_cariow_program_sedenion_product]: the program computes the
      Cayley-Dickson sedenion product of [sed_mul], by
      [C1636_cariow2013_sedenion_mul_eq], with 122 multiplications of two
      variable quantities, against 16 * 16 = 256 for the coordinate
      expansion b_i * a_j;
    - [cariow_program_outputs]: the program has sixteen output registers;
    - [control_extra_multiply_count] and its neighbors: the known-bad
      control.  [add_multiply cariow_program], the schedule with one extra
      [IMul] appended, reports 123 against 122, so [mul_count] sees a
      multiplication; a program that only scales and adds reports 0.

    The proof of [cariow_program_correct] unfolds [run] on symbolic
    coordinates and closes each output by conversion: the generated
    program performs each addition, subtraction, scaling and product of
    the schedule in the same operand order, and the one difference, the
    first coordinate -(t0 - s0) against s0 - t0, is closed by
    [Ropp_minus_distr].  No field or ring normalization is involved.

    Scope.  The count is that of this program.  It is an upper bound for
    the multiplicative complexity of the sedenion product as a bilinear
    map and claims no minimality.  Scaling by a constant, addition and
    subtraction are not counted, as in C1636_Cariow2013SedenionSchedule and
    C1636_ScheduleProductCount.  The cost model is the instruction set
    above; [IScale] takes any real constant, so the count says nothing
    about the cost of forming 1/16 or 2.  The figure 256 is the number of
    products b_i * a_j of the coordinate expansion, read from its formula;
    no program of this module computes the coordinate expansion. *)

From Stdlib Require Import List Reals Lia Arith.
From OpenGororoba Require Import Prelude CayleyDicksonAlgebra Sedenion.
From OpenGororobaVerified Require Import C1636_Cariow2013SedenionSchedule
  C1636_ScheduleProductCount.
Import ListNotations.

Local Open Scope nat_scope.

Inductive instr : Type :=
| ILoadA (i : nat)
| ILoadB (j : nat)
| IAdd (r s : nat)
| ISub (r s : nat)
| IScale (k : R) (r : nat)
| IMul (r s : nat).

Record program : Type := mkProgram {
  prog_instrs : list instr;
  prog_outs : list nat
}.

Definition reg (env : list R) (r : nat) : R := nth r env 0%R.

Definition step (a b : R16) (env : list R) (i : instr) : R :=
  match i with
  | ILoadA k => r16_nth a k
  | ILoadB k => r16_nth b k
  | IAdd r s => (reg env r + reg env s)%R
  | ISub r s => (reg env r - reg env s)%R
  | IScale k r => (k * reg env r)%R
  | IMul r s => (reg env r * reg env s)%R
  end.

Fixpoint exec (a b : R16) (code : list instr) (env : list R) : list R :=
  match code with
  | [] => env
  | i :: rest => exec a b rest (env ++ [step a b env i])
  end.

Definition run (p : program) (a b : R16) : list R :=
  map (reg (exec a b (prog_instrs p) [])) (prog_outs p).

Fixpoint instrs_mul_count (code : list instr) : nat :=
  match code with
  | [] => 0
  | IMul _ _ :: rest => S (instrs_mul_count rest)
  | _ :: rest => instrs_mul_count rest
  end.

Definition mul_count (p : program) : nat := instrs_mul_count (prog_instrs p).

Lemma instrs_mul_count_app :
  forall l m, instrs_mul_count (l ++ m) = instrs_mul_count l + instrs_mul_count m.
Proof.
  induction l as [|i l IH]; intros m; [reflexivity |].
  destruct i; simpl; rewrite ?IH; reflexivity.
Qed.

(** Generators of the stages. *)

Definition load_a : list instr := map ILoadA (seq 0 16).
Definition load_b : list instr := map ILoadB (seq 0 16).

(** One butterfly stage of stride d on the registers x: output i adds
    x_i and x_(i+d) when bit d of i is clear, and subtracts x_i from
    x_(i-d) when it is set. *)
Definition butterfly (d : nat) (x : list nat) : list instr :=
  map (fun i =>
         if Nat.eqb ((i / d) mod 2) 0
         then IAdd (nth i x 0) (nth (i + d) x 0)
         else ISub (nth (i - d) x 0) (nth i x 0))
      (seq 0 16).

Definition forward_strides : list nat := [8; 4; 2; 1].
Definition reverse_strides : list nat := [1; 2; 4; 8].

(** A pass appends its instructions to the program text p and returns the
    new text with the registers that hold its sixteen results. *)
Fixpoint hadamard_pass (ds : list nat) (p : list instr) (x : list nat)
  : list instr * list nat :=
  match ds with
  | [] => (p, x)
  | d :: rest =>
      hadamard_pass rest (p ++ butterfly d x) (seq (length p) 16)
  end.

Definition scale_pass (k : R) (p : list instr) (x : list nat)
  : list instr * list nat :=
  (p ++ map (IScale k) x, seq (length p) 16).

Definition pointwise_pass (p : list instr) (x y : list nat)
  : list instr * list nat :=
  (p ++ map (fun rs => IMul (fst rs) (snd rs)) (combine x y),
   seq (length p) 16).

(** The block of a row with n instructions before it: the products b_j * a_i
    of the row at registers n ..., the chain of additions that sums them,
    and the scaling by 2. *)
Definition row_instrs (n : nat) (row : list (nat * nat)) : list instr :=
  let len := length row in
  map (fun q => IMul (16 + fst q) (snd q)) row ++
  map (fun k => IAdd (if Nat.eqb k 1 then n else n + len + k - 2) (n + k))
      (seq 1 (len - 1)) ++
  [IScale 2%R (n + 2 * len - 2)].

Fixpoint sparse_pass (rows : list (list (nat * nat))) (p : list instr)
  (outs : list nat) : list instr * list nat :=
  match rows with
  | [] => (p, outs)
  | row :: rest =>
      let q := p ++ row_instrs (length p) row in
      sparse_pass rest q (outs ++ [length q - 1])
  end.

Definition combine_pass (p : list instr) (t s : list nat) : list instr :=
  p ++ map (fun i =>
              if Nat.eqb i 0
              then ISub (nth i s 0) (nth i t 0)
              else ISub (nth i t 0) (nth i s 0))
           (seq 0 16).

Definition cariow_program : program :=
  let p0 := load_a ++ load_b in
  let '(p1, ha) := hadamard_pass forward_strides p0 (seq 0 16) in
  let '(p2, hb) := hadamard_pass forward_strides p1 (seq 16 16) in
  let '(p3, hbs) := scale_pass (/ 16)%R p2 hb in
  let '(p4, pw) := pointwise_pass p3 ha hbs in
  let '(p5, t) := hadamard_pass reverse_strides p4 pw in
  let '(p6, s) := sparse_pass sparse_terms p5 [] in
  let p7 := combine_pass p6 t s in
  mkProgram p7 (seq (length p6) 16).

Definition r16_to_list (x : R16) : list R := map (r16_nth x) (seq 0 16).

Definition r16_of_list (l : list R) : R16 :=
  mkR16 (nth 0 l 0%R) (nth 1 l 0%R) (nth 2 l 0%R) (nth 3 l 0%R)
        (nth 4 l 0%R) (nth 5 l 0%R) (nth 6 l 0%R) (nth 7 l 0%R)
        (nth 8 l 0%R) (nth 9 l 0%R) (nth 10 l 0%R) (nth 11 l 0%R)
        (nth 12 l 0%R) (nth 13 l 0%R) (nth 14 l 0%R) (nth 15 l 0%R).

Lemma r16_of_list_to_list : forall x, r16_of_list (r16_to_list x) = x.
Proof. intros [x0 x1 x2 x3 x4 x5 x6 x7 x8 x9 x10 x11 x12 x13 x14 x15]; reflexivity. Qed.

Theorem cariow_program_mul_count : mul_count cariow_program = 122.
Proof. vm_compute. reflexivity. Qed.

Theorem cariow_program_outputs : length (prog_outs cariow_program) = 16.
Proof. vm_compute. reflexivity. Qed.

Theorem cariow_program_correct :
  forall a b : R16,
    run cariow_program a b = r16_to_list (r16_cariow2013_sedenion_mul a b).
Proof.
  intros [a0 a1 a2 a3 a4 a5 a6 a7 a8 a9 a10 a11 a12 a13 a14 a15]
         [b0 b1 b2 b3 b4 b5 b6 b7 b8 b9 b10 b11 b12 b13 b14 b15].
  lazy.
  apply (f_equal2 cons); [symmetry; apply Ropp_minus_distr |].
  do 15 (apply (f_equal2 cons); [reflexivity |]).
  reflexivity.
Qed.

Theorem C1636_cariow_program_sedenion_product :
  (forall a b : R16,
     r16_to_sed (r16_of_list (run cariow_program a b)) =
     sed_mul (r16_to_sed a) (r16_to_sed b)) /\
  mul_count cariow_program = 122 /\
  122 < 16 * 16.
Proof.
  split; [| split; [exact cariow_program_mul_count | lia]].
  intros a b.
  rewrite cariow_program_correct, r16_of_list_to_list.
  apply C1636_cariow2013_sedenion_mul_eq.
Qed.

(** Known-bad controls: programs whose count differs from that of the
    schedule by the instruction that was added. *)

Definition one_multiply_program : program :=
  mkProgram [ILoadA 0; ILoadB 0; IMul 0 1] [2].

Definition two_multiply_program : program :=
  mkProgram [ILoadA 0; ILoadB 0; IMul 0 1; IMul 0 1] [2; 3].

Definition scaling_program : program :=
  mkProgram [ILoadA 0; IScale 2%R 0; IAdd 0 1] [2].

(** [add_multiply p] is p with one more [IMul] at the end. *)
Definition add_multiply (p : program) : program :=
  mkProgram (prog_instrs p ++ [IMul 0 16]) (prog_outs p).

Lemma add_multiply_count :
  forall p : program, mul_count (add_multiply p) = S (mul_count p).
Proof.
  intros p. unfold mul_count, add_multiply.
  cbn [prog_instrs]. rewrite instrs_mul_count_app. cbn [instrs_mul_count].
  lia.
Qed.

Example control_one_multiply_count : mul_count one_multiply_program = 1.
Proof. reflexivity. Qed.

Example control_two_multiply_count : mul_count two_multiply_program = 2.
Proof. reflexivity. Qed.

Example control_scaling_count : mul_count scaling_program = 0.
Proof. reflexivity. Qed.

(** The schedule with one extra multiply reports 123, against 122. *)
Example control_extra_multiply_count :
  mul_count (add_multiply cariow_program) = 123 /\
  mul_count (add_multiply cariow_program) <> mul_count cariow_program.
Proof.
  rewrite add_multiply_count, cariow_program_mul_count. split; [reflexivity | lia].
Qed.

Example control_one_multiply_run :
  forall a b : R16,
    run one_multiply_program a b = [(r16_nth a 0 * r16_nth b 0)%R].
Proof. intros a b. cbv [run one_multiply_program prog_instrs prog_outs exec step reg app nth map]. reflexivity. Qed.
