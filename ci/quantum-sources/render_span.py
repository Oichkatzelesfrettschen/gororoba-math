ROCQ_NAME = "CdTowerG2DerivationSpan.v"
SPAN_RECORD = HERE / "span.json"
# The location of the Rocq source; --rocq replaces it.
ROCQ_FILE: Path = quantum_checkout.ROCQ / ROCQ_NAME
DIMENSION = 16
UNKNOWNS = DIMENSION * DIMENSION
TABLES = 14
EQUATIONS = UNKNOWNS - TABLES
SPAN_KEYS = {"schema", "d", "seed", "equations", "p_sparse"}


def read_span(record: object) -> dict[str, Any]:
    """The span record after the checks of this module's docstring; any other shape raises RuntimeError."""
    record = exact_keys(record, SPAN_KEYS, "span record")
    if record["schema"] != SCHEMA:
        raise RuntimeError(f"span record: schema {record['schema']!r}, expected {SCHEMA!r}")
    if exact_integer(record["d"], "span record, d") < 1:
        raise RuntimeError(f"span record: the scalar {record['d']} is not positive")
    if exact_integer(record["seed"], "span record, seed") < 0:
        raise RuntimeError(f"span record: the seed {record['seed']} is negative")
    equations = record["equations"]
    if not isinstance(equations, list) or len(equations) != EQUATIONS:
        raise RuntimeError(f"span record: the record does not list {EQUATIONS} equations")
    seen = set()
    for position, triple in enumerate(equations):
        where = f"span record, equation {position}"
        if not isinstance(triple, list) or len(triple) != 3:
            raise RuntimeError(f"{where}: {triple!r} is not a triple")
        values = tuple(exact_integer(value, where) for value in triple)
        if any(not 0 <= value < DIMENSION for value in values):
            raise RuntimeError(f"{where}: {values} leaves 0 to {DIMENSION - 1}")
        if values in seen:
            raise RuntimeError(f"{where}: {values} repeats")
        seen.add(values)
    lines = record["p_sparse"]
    if not isinstance(lines, list) or len(lines) != UNKNOWNS:
        raise RuntimeError(f"span record: P does not hold {UNKNOWNS} lines")
    for number, line in enumerate(lines):
        if not isinstance(line, list):
            raise RuntimeError(f"span record: line {number} of P is not a list")
        previous = -1
        for position, item in enumerate(line):
            where = f"span record, line {number} of P, item {position}"
            if not isinstance(item, list) or len(item) != 2 or not isinstance(item[1], list) or len(item[1]) != 2:
                raise RuntimeError(f"{where}: {item!r} is not [column, [real, imaginary]]")
            column = exact_integer(item[0], where)
            if not previous < column < EQUATIONS:
                raise RuntimeError(f"{where}: column {column} is out of range, repeated or out of order")
            previous = column
            exact_integer(item[1][0], where)
            exact_integer(item[1][1], where)
    return record


