"""Render CdTowerG2DerivationSpan.v from the splitting certificate of span_certificate.py.

The reader of `span.json` accepts exactly the shape span_certificate.py writes: the key set and the schema, a
positive integer scalar d, 242 distinct equation triples (a, b, c) with entries in 0 to 15, and 256 lines of P, each
a list of (column, (real, imaginary)) items whose columns are integers that increase within 0 to 241. A float, a
boolean, a string, a missing or an extra key, another count or a repeated or out-of-range index raises.

The Rocq file is a source of this repository (`rocq/quantum`). The module constant `ROCQ_FILE` names it; `main`
compares the rendering with it (`--check`) or replaces it (`--write`):

    GOROROBA_QUANTUM=PATH "$PYTHON" ci/quantum-sources/render_span.py --check

`--rocq DIRECTORY` names another directory that holds the file and `--record` replaces the tracked `span.json`.
"""

