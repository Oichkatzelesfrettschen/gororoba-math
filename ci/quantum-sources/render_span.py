def render(record: dict[str, Any]) -> str:
    """The text of CdTowerG2DerivationSpan.v for a record that read_span accepted."""
    equations = [f"({a}, {b}, {c})%nat" for a, b, c in record["equations"]]
    back = ";\n".join(
        wrapped([f"({column}%nat, ({value[0]}, {value[1]}))" for column, value in line], "    ", "[", "]")
        for line in record["p_sparse"]
    )
    tables = (
        "Definition equations : list (nat * nat * nat) :=\n"
        + wrapped(equations, "  ", "[", "].")
        + "\n\nDefinition back : list (list (nat * (Z * Z))) :=\n  [\n"
        + back
        + "\n  ].\n\n"
        + f"Definition scalar : Z * Z := ({record['d']}, 0).\n"
    )
    return HEADER + tables + BODY.replace("EQUATIONS", str(len(equations)))


def replace_text(path: Path, text: str) -> None:
    """Replace `path` with `text` through a scratch file created exclusively beside it, so that a reader sees the
    old bytes or the new ones, with the mode of an existing `path` (0644 otherwise)."""
    mode = path.stat().st_mode & 0o777 if path.is_file() else 0o644
    descriptor, scratch = tempfile.mkstemp(prefix=path.name + ".", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            stream.write(text)
        os.chmod(scratch, mode)
        os.replace(scratch, path)
    except BaseException:
        Path(scratch).unlink(missing_ok=True)
        raise


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--record", type=Path, default=SPAN_RECORD, help="the span record (JSON)")
    parser.add_argument("--rocq", type=Path, help="directory of the rendered Rocq file, instead of rocq/quantum")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="compare with the file on disk, write nothing")
    mode.add_argument("--write", action="store_true", help="write the Rocq file")
    arguments = parser.parse_args(argv)
    target = ROCQ_FILE if arguments.rocq is None else arguments.rocq / ROCQ_NAME
    record = read_span(json.loads(arguments.record.read_text(encoding="utf-8")))
    text = render(record)
    summary = f"{len(record['equations'])} equations, d = {record['d']}"
    if arguments.check:
        same = target.is_file() and target.read_text(encoding="utf-8") == text
        print(f"{'ok' if same else 'DIFFERS'} {target.name}: {summary}")
        return 0 if same else 1
    replace_text(target, text)
    print(f"wrote {target.name}: {len(text)} bytes, {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
